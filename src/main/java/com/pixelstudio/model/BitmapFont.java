package com.pixelstudio.model;

import java.util.HashMap;
import java.util.Map;

/**
 * 一个 3x5 的迷你点阵字体，用来在画布上"写字"。
 *
 * <p>每个字符用 5 行字符串描述，{@code '#'} 表示这个点要涂色，其它表示留空。比如 {@code A}：
 * <pre>
 *   ###
 *   #.#
 *   ###
 *   #.#
 *   #.#
 * </pre>
 *
 * <p><b>这个类想让你练到什么？</b>
 * <ul>
 *   <li><b>static 初始化块</b>：类加载的时候自动跑一次，把字形表填好；</li>
 *   <li><b>Map 作为查找表</b>：字符 -&gt; 字形，O(1) 查找；</li>
 *   <li><b>不可变集合</b>：建好之后只读，不对外暴露，防止别人改坏；</li>
 *   <li><b>静态常量放前面</b>：先声明 GLYPH_W / GLYPH_H，再在静态块里用它们，顺序不能反。</li>
 * </ul>
 */
public final class BitmapFont {

    /** 每个字形的宽度（像素）。 */
    public static final int GLYPH_W = 3;

    /** 每个字形的高度（像素）。 */
    public static final int GLYPH_H = 5;

    /** 字与字之间留 1 像素空隙，否则 "AA" 会挤成一坨。 */
    public static final int SPACING = 1;

    private static final Map<Character, String[]> FONT = new HashMap<>();

    static {
        def('A', "###", "#.#", "###", "#.#", "#.#");
        def('B', "##.", "#.#", "##.", "#.#", "##.");
        def('C', "###", "#..", "#..", "#..", "###");
        def('D', "##.", "#.#", "#.#", "#.#", "##.");
        def('E', "###", "#..", "##.", "#..", "###");
        def('F', "###", "#..", "##.", "#..", "#..");
        def('G', "###", "#..", "#.#", "#.#", "###");
        def('H', "#.#", "#.#", "###", "#.#", "#.#");
        def('I', "###", ".#.", ".#.", ".#.", "###");
        def('J', "..#", "..#", "..#", "#.#", ".#.");
        def('K', "#.#", "#.#", "##.", "#.#", "#.#");
        def('L', "#..", "#..", "#..", "#..", "###");
        def('M', "#.#", "###", "###", "#.#", "#.#");
        def('N', "#.#", "##.", "#.#", "#.#", "#.#");
        def('O', "###", "#.#", "#.#", "#.#", "###");
        def('P', "###", "#.#", "###", "#..", "#..");
        def('Q', "###", "#.#", "#.#", "##.", ".##");
        def('R', "###", "#.#", "###", "##.", "#.#");
        def('S', ".##", "#..", ".##", "..#", "##.");
        def('T', "###", ".#.", ".#.", ".#.", ".#.");
        def('U', "#.#", "#.#", "#.#", "#.#", "###");
        def('V', "#.#", "#.#", "#.#", "#.#", ".#.");
        def('W', "#.#", "#.#", "###", "###", "#.#");
        def('X', "#.#", "#.#", ".#.", "#.#", "#.#");
        def('Y', "#.#", "#.#", ".#.", ".#.", ".#.");
        def('Z', "###", "..#", ".#.", "#..", "###");

        def('0', "###", "#.#", "#.#", "#.#", "###");
        def('1', ".#.", "##.", ".#.", ".#.", "###");
        def('2', "##.", "..#", ".#.", "#..", "###");
        def('3', "###", "..#", ".##", "..#", "###");
        def('4', "#.#", "#.#", "###", "..#", "..#");
        def('5', "###", "#..", "###", "..#", "###");
        def('6', ".##", "#..", "###", "#.#", "###");
        def('7', "###", "..#", ".#.", ".#.", ".#.");
        def('8', "###", "#.#", "###", "#.#", "###");
        def('9', "###", "#.#", "###", "..#", "##.");

        def(' ', "...", "...", "...", "...", "...");
        def('-', "...", "...", "###", "...", "...");
        def('.', "...", "...", "...", "...", ".#.");
        def(',', "...", "...", "...", ".#.", "#..");
        def('!', ".#.", ".#.", ".#.", "...", ".#.");
        def('?', "##.", "..#", ".#.", "...", ".#.");
        def(':', "...", ".#.", "...", ".#.", "...");
        def(';', "...", ".#.", "...", ".#.", "#..");
        def('/', "..#", "..#", ".#.", "#..", "#..");
        def('\\', "#..", "#..", ".#.", "..#", "..#");
        def('+', "...", ".#.", "###", ".#.", "...");
        def('=', "...", "###", "...", "###", "...");
        def('<', "..#", ".#.", "#..", ".#.", "..#");
        def('>', "#..", ".#.", "..#", ".#.", "#..");
        def('*', "#.#", "###", "#.#", "...", "...");
        def('#', "#.#", "###", "#.#", "###", "#.#");
        def('%', "#.#", "..#", ".#.", "#..", "#.#");
        def('@', "###", "#.#", "###", "#..", "###");
        def('&', "##.", "#..", "##.", "#.#", ".##");
        def('_', "...", "...", "...", "...", "###");
        def('\'', ".#.", ".#.", "...", "...", "...");
        def('"', "#.#", "#.#", "...", "...", "...");
        def('(', "..#", ".#.", ".#.", ".#.", "..#");
        def(')', "#..", ".#.", ".#.", ".#.", "#..");
        def('[', "###", "#..", "#..", "#..", "###");
        def(']', "###", "..#", "..#", "..#", "###");
    }

    private BitmapFont() {
        // 工具类不需要被 new 出来，私有构造器是个好习惯
    }

    private static void def(char ch, String... rows) {
        FONT.put(ch, rows);
    }

    /**
     * 查某个字符的字形。
     *
     * @return 5 行字形数据；字体里没有这个字符时返回 {@code null}（调用方自己决定跳过还是画方块）
     */
    public static String[] glyphOf(char ch) {
        return FONT.get(Character.toUpperCase(ch));
    }

    /** 这个字符字体里认不认识。 */
    public static boolean supports(char ch) {
        return glyphOf(ch) != null;
    }

    /** 画一串文字总共需要多宽（像素）。 */
    public static int textWidth(String text) {
        if (text == null || text.isEmpty()) {
            return 0;
        }
        return text.length() * GLYPH_W + (text.length() - 1) * SPACING;
    }
}
